-- Officers, the academy that graduates them, and airgroup/division grouping.
-- Applied by drizzle-kit push; kept here for review.

CREATE TABLE IF NOT EXISTS commanders (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  state_id integer NOT NULL REFERENCES states(id) ON DELETE CASCADE,
  owner_id text NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
  name varchar(100) NOT NULL,
  trait_ids jsonb NOT NULL DEFAULT '[]'::jsonb,
  portrait integer NOT NULL DEFAULT 0,
  health integer NOT NULL DEFAULT 100,
  experience integer NOT NULL DEFAULT 0,
  alive boolean NOT NULL DEFAULT true,
  graduated_at timestamp NOT NULL DEFAULT now(),
  created_at timestamp NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_commander_state ON commanders (state_id);

CREATE TABLE IF NOT EXISTS commander_trainings (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  state_id integer NOT NULL REFERENCES states(id) ON DELETE CASCADE,
  owner_id text NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
  completed_at timestamp,
  created_at timestamp NOT NULL DEFAULT now(),
  completes_at timestamp NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_commander_training_due ON commander_trainings (completed_at, completes_at);
CREATE INDEX IF NOT EXISTS idx_commander_training_state ON commander_trainings (state_id);

ALTER TABLE fleets ADD COLUMN IF NOT EXISTS commander_id integer REFERENCES commanders(id) ON DELETE SET NULL;

DO $$ BEGIN
  CREATE TYPE unit_group_kind AS ENUM ('airgroup','division');
EXCEPTION WHEN duplicate_object THEN null; END $$;

CREATE TABLE IF NOT EXISTS unit_groups (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  state_id integer NOT NULL REFERENCES states(id) ON DELETE CASCADE,
  owner_id text NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
  kind unit_group_kind NOT NULL,
  name varchar(100) NOT NULL,
  commander_id integer REFERENCES commanders(id) ON DELETE SET NULL,
  created_at timestamp NOT NULL DEFAULT now(),
  updated_at timestamp NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_unit_group_state ON unit_groups (state_id);
CREATE INDEX IF NOT EXISTS idx_unit_group_commander ON unit_groups (commander_id);

ALTER TABLE military_units ADD COLUMN IF NOT EXISTS group_id integer REFERENCES unit_groups(id) ON DELETE SET NULL;
