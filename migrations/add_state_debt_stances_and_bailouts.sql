-- State debt, civilian opinion of foreign states and treasury bailouts.
-- Idempotent so it can be applied more than once.
ALTER TABLE state_treasury ADD COLUMN IF NOT EXISTS debt bigint DEFAULT 0 NOT NULL;

CREATE TABLE IF NOT EXISTS civilian_stances (
	id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	observer_state_id integer NOT NULL REFERENCES states(id) ON DELETE CASCADE,
	target_state_id integer NOT NULL REFERENCES states(id) ON DELETE CASCADE,
	stance integer DEFAULT 0 NOT NULL,
	updated_at timestamp DEFAULT now() NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_civilian_stance_pair
	ON civilian_stances (observer_state_id, target_state_id);
CREATE INDEX IF NOT EXISTS idx_civilian_stance_target
	ON civilian_stances (target_state_id);

CREATE TABLE IF NOT EXISTS state_bailouts (
	id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	donor_state_id integer NOT NULL REFERENCES states(id) ON DELETE CASCADE,
	recipient_state_id integer NOT NULL REFERENCES states(id) ON DELETE CASCADE,
	amount bigint NOT NULL,
	debt_relieved bigint DEFAULT 0 NOT NULL,
	authorized_by text REFERENCES account(id) ON DELETE SET NULL,
	created_at timestamp DEFAULT now() NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_bailout_recipient ON state_bailouts (recipient_state_id);
CREATE INDEX IF NOT EXISTS idx_bailout_donor ON state_bailouts (donor_state_id);

CREATE TABLE IF NOT EXISTS user_firsts (
	id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	user_id text NOT NULL REFERENCES account(id) ON DELETE CASCADE,
	kind varchar(40) NOT NULL,
	reached_at timestamp DEFAULT now() NOT NULL,
	seen_at timestamp
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_user_first_user_kind ON user_firsts (user_id, kind);
