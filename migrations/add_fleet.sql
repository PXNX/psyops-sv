EXCEPTION WHEN duplicate_object THEN null; END $$;

CREATE TABLE IF NOT EXISTS air_missions (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  state_id integer NOT NULL REFERENCES states(id) ON DELETE CASCADE,
  unit_id integer NOT NULL REFERENCES military_units(id) ON DELETE CASCADE,
  ordered_by text REFERENCES accounts(id) ON DELETE SET NULL,
  kind varchar(40) NOT NULL,
  source_region_id integer REFERENCES regions(id) ON DELETE SET NULL,
  target_region_id integer REFERENCES regions(id) ON DELETE SET NULL,
  q integer,
  r integer,
  fuel_cost integer NOT NULL,
  status air_mission_status NOT NULL DEFAULT 'in_progress',
  result jsonb,
  launched_at timestamp NOT NULL DEFAULT now(),
  completes_at timestamp NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_air_mission_state ON air_missions (state_id, launched_at);
CREATE INDEX IF NOT EXISTS idx_air_mission_due ON air_missions (status, completes_at);

DO $$ BEGIN CREATE TYPE sea_intel_status AS ENUM ('in_progress','completed');
EXCEPTION WHEN duplicate_object THEN null; END $$;

CREATE TABLE IF NOT EXISTS sea_intel_missions (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  state_id integer NOT NULL REFERENCES states(id) ON DELETE CASCADE,
  launched_by text NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
  sensor varchar(30) NOT NULL,
  q integer NOT NULL,
  r integer NOT NULL,
  cost integer NOT NULL,
  status sea_intel_status NOT NULL DEFAULT 'in_progress',
  findings jsonb,
  launched_at timestamp NOT NULL DEFAULT now(),
  completes_at timestamp NOT NULL,
  observed_at timestamp
);
CREATE INDEX IF NOT EXISTS idx_sea_intel_state ON sea_intel_missions (state_id, launched_at);
CREATE INDEX IF NOT EXISTS idx_sea_intel_hex ON sea_intel_missions (q, r, observed_at);
CREATE INDEX IF NOT EXISTS idx_sea_intel_due ON sea_intel_missions (status, completes_at);

