-- Fleet at sea: a hex sea grid with movable ships, ports, docks, minefields
-- and a docking queue. Applied by drizzle-kit push; kept here for review.

DO $$ BEGIN
  CREATE TYPE ship_class AS ENUM (
    'carrier','frigate','helipad','support_ship','corvette','destroyer',
    'light_aa','gnss_jammer','torpedo_sub','vls_sub','container_ship','roro_ferry','tanker'
  );
EXCEPTION WHEN duplicate_object THEN null; END $$;

DO $$ BEGIN CREATE TYPE ship_status AS ENUM ('idle','moving','repairing','sunk');
EXCEPTION WHEN duplicate_object THEN null; END $$;
DO $$ BEGIN CREATE TYPE dock_queue_kind AS ENUM ('construct','repair');
EXCEPTION WHEN duplicate_object THEN null; END $$;
DO $$ BEGIN CREATE TYPE dock_queue_status AS ENUM ('queued','building','done','cancelled');
EXCEPTION WHEN duplicate_object THEN null; END $$;

CREATE TABLE IF NOT EXISTS sea_ports (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  state_id integer NOT NULL REFERENCES states(id) ON DELETE CASCADE,
  region_id integer REFERENCES regions(id) ON DELETE SET NULL,
  q integer NOT NULL,
  r integer NOT NULL,
  name varchar(100) NOT NULL,
  level integer NOT NULL DEFAULT 1,
  fuel_stock integer NOT NULL DEFAULT 0,
  stock jsonb NOT NULL DEFAULT '{}'::jsonb,
  built_by text REFERENCES accounts(id) ON DELETE SET NULL,
  created_at timestamp NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_sea_port_hex ON sea_ports (q, r);
CREATE INDEX IF NOT EXISTS idx_sea_port_state ON sea_ports (state_id);

CREATE TABLE IF NOT EXISTS sea_docks (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  port_id integer NOT NULL REFERENCES sea_ports(id) ON DELETE CASCADE,
  state_id integer NOT NULL REFERENCES states(id) ON DELETE CASCADE,
  q integer NOT NULL,
  r integer NOT NULL,
  level integer NOT NULL DEFAULT 1,
  built_by text REFERENCES accounts(id) ON DELETE SET NULL,
  created_at timestamp NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_sea_dock_port ON sea_docks (port_id);
CREATE INDEX IF NOT EXISTS idx_sea_dock_state ON sea_docks (state_id);

CREATE TABLE IF NOT EXISTS fleet_ships (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  state_id integer NOT NULL REFERENCES states(id) ON DELETE CASCADE,
  owner_id text NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
  dock_id integer REFERENCES sea_docks(id) ON DELETE SET NULL,
  name varchar(100) NOT NULL,
  ship_class ship_class NOT NULL,
  q integer NOT NULL,
  r integer NOT NULL,
  health integer NOT NULL DEFAULT 100,
  fuel integer NOT NULL DEFAULT 0,
  cargo_type varchar(40),
  cargo_amount integer NOT NULL DEFAULT 0,
  status ship_status NOT NULL DEFAULT 'idle',
  order_path jsonb,
  leg_starts_at timestamp,
  leg_arrives_at timestamp,
  created_at timestamp NOT NULL DEFAULT now(),
  updated_at timestamp NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_fleet_ship_state ON fleet_ships (state_id);
CREATE INDEX IF NOT EXISTS idx_fleet_ship_hex ON fleet_ships (q, r);

CREATE TABLE IF NOT EXISTS fleet_dock_queue (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dock_id integer NOT NULL REFERENCES sea_docks(id) ON DELETE CASCADE,
  state_id integer NOT NULL REFERENCES states(id) ON DELETE CASCADE,
  kind dock_queue_kind NOT NULL,
  ship_class ship_class,
  ship_id integer REFERENCES fleet_ships(id) ON DELETE SET NULL,
  ordered_by text REFERENCES accounts(id) ON DELETE SET NULL,
  cost integer NOT NULL,
  status dock_queue_status NOT NULL DEFAULT 'queued',
  queued_at timestamp NOT NULL DEFAULT now(),
  starts_at timestamp,
  completes_at timestamp
);
CREATE INDEX IF NOT EXISTS idx_fleet_queue_dock ON fleet_dock_queue (dock_id, status, id);
CREATE INDEX IF NOT EXISTS idx_fleet_queue_state ON fleet_dock_queue (state_id);

CREATE TABLE IF NOT EXISTS naval_mines (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  state_id integer NOT NULL REFERENCES states(id) ON DELETE CASCADE,
  q integer NOT NULL,
  r integer NOT NULL,
  strength integer NOT NULL DEFAULT 100,
  laid_by text REFERENCES accounts(id) ON DELETE SET NULL,
  laid_at timestamp NOT NULL DEFAULT now(),
  expires_at timestamp NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_naval_mine_hex ON naval_mines (q, r);
CREATE INDEX IF NOT EXISTS idx_naval_mine_state ON naval_mines (state_id);

CREATE TABLE IF NOT EXISTS fleet_events (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  state_id integer REFERENCES states(id) ON DELETE CASCADE,
  kind varchar(40) NOT NULL,
  q integer,
  r integer,
  message text,
  data jsonb,
  created_at timestamp NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_fleet_event_state ON fleet_events (state_id, created_at);
CREATE INDEX IF NOT EXISTS idx_fleet_event_hex ON fleet_events (q, r);

