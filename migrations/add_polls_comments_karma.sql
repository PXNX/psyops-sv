-- Post polls, reader comments and community karma. Karma is deliberately
-- separate from civilian reputation, which comes from opinion in the world.

ALTER TABLE user_profiles ADD COLUMN IF NOT EXISTS karma integer NOT NULL DEFAULT 0;

CREATE TABLE IF NOT EXISTS polls (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  article_id integer NOT NULL REFERENCES articles(id) ON DELETE CASCADE,
  question varchar(200) NOT NULL,
  options jsonb NOT NULL,
  created_by text NOT NULL REFERENCES account(id) ON DELETE CASCADE,
  closes_at timestamp,
  created_at timestamp NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_poll_article ON polls (article_id);

CREATE TABLE IF NOT EXISTS poll_votes (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  poll_id integer NOT NULL REFERENCES polls(id) ON DELETE CASCADE,
  user_id text NOT NULL REFERENCES account(id) ON DELETE CASCADE,
  option_index integer NOT NULL,
  created_at timestamp NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_poll_vote ON poll_votes (poll_id, user_id);

CREATE TABLE IF NOT EXISTS comments (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  article_id integer NOT NULL REFERENCES articles(id) ON DELETE CASCADE,
  author_id text NOT NULL REFERENCES account(id) ON DELETE CASCADE,
  content text NOT NULL,
  created_at timestamp NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_comment_article ON comments (article_id, id);

CREATE TABLE IF NOT EXISTS comment_votes (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  comment_id integer NOT NULL REFERENCES comments(id) ON DELETE CASCADE,
  user_id text NOT NULL REFERENCES account(id) ON DELETE CASCADE,
  created_at timestamp NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_comment_vote ON comment_votes (comment_id, user_id);

ALTER TYPE report_target_type ADD VALUE IF NOT EXISTS 'comment';
ALTER TYPE report_target_type ADD VALUE IF NOT EXISTS 'article';
