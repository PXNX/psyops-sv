-- Fleet groups: ships can be organised into a fleet and ordered to hold an
-- area of sea. Applied by drizzle-kit push; kept here for review.

CREATE TABLE IF NOT EXISTS fleets (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  state_id integer NOT NULL REFERENCES states(id) ON DELETE CASCADE,
  owner_id text NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
  name varchar(100) NOT NULL,
  created_at timestamp NOT NULL DEFAULT now(),
  updated_at timestamp NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_fleet_state ON fleets (state_id);

CREATE TABLE IF NOT EXISTS fleet_hexes (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fleet_id integer NOT NULL REFERENCES fleets(id) ON DELETE CASCADE,
  q integer NOT NULL,
  r integer NOT NULL,
  assigned_at timestamp NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_fleet_hex ON fleet_hexes (fleet_id, q, r);
CREATE INDEX IF NOT EXISTS idx_fleet_hex_hex ON fleet_hexes (q, r);

ALTER TABLE fleet_ships ADD COLUMN IF NOT EXISTS fleet_id integer REFERENCES fleets(id) ON DELETE SET NULL;
CREATE INDEX IF NOT EXISTS idx_fleet_ship_fleet ON fleet_ships (fleet_id);
